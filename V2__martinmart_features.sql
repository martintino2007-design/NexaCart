-- MartinMart feature expansion: wishlist, addresses, coupons, audit trail and richer reviews.
CREATE TABLE IF NOT EXISTS addresses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL,
 full_name VARCHAR(100) NOT NULL,
 phone VARCHAR(30) NOT NULL,
 address_line VARCHAR(300) NOT NULL,
 city VARCHAR(100) NOT NULL,
 pin_code VARCHAR(10) NOT NULL,
 is_default BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_addresses_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_addresses_user ON addresses(user_id);
CREATE TABLE IF NOT EXISTS wishlists (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_wishlist_user FOREIGN KEY (user_id) REFERENCES users(id),
 CONSTRAINT fk_wishlist_product FOREIGN KEY (product_id) REFERENCES products(id),
 CONSTRAINT uq_wishlist UNIQUE(user_id, product_id)
);
CREATE TABLE IF NOT EXISTS coupons (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE,
 discount_amount DECIMAL(10,2) NOT NULL DEFAULT 0,
 discount_percent DECIMAL(5,2) NOT NULL DEFAULT 0,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 expires_at TIMESTAMP NULL
);
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT,
 action VARCHAR(80) NOT NULL,
 details VARCHAR(1000),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_audit_user FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_logs(created_at);
ALTER TABLE reviews ADD COLUMN IF NOT EXISTS verified_purchase BOOLEAN DEFAULT FALSE;
ALTER TABLE reviews ADD COLUMN IF NOT EXISTS seller_reply VARCHAR(1000);
